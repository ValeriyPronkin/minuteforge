"""Параметры расчёта: значения по умолчанию, файл, переменные окружения.

Приоритет — от низкого к высокому: умолчания, ``config.yaml``, переменные
окружения с префиксом ``MINUTEFORGE_``. Секреты живут только в окружении: токен
HuggingFace однажды уже был вписан в код и в файл рядом с ним, и это стоило
отзыва токена.
"""

from __future__ import annotations

import os
from dataclasses import asdict, dataclass, field, fields
from pathlib import Path
from typing import Any

try:
    import yaml
except Exception:  # pragma: no cover
    yaml = None

#: Переменные окружения, откуда берутся секреты. В ``config.yaml`` им не место.
HF_TOKEN_ENV = "HF_TOKEN"
#: Ключ к внешней модели. Тоже только из окружения и по той же причине.
LLM_KEY_ENV = "MINUTEFORGE_LLM_KEY"


@dataclass
class Settings:
    """Параметры распознавания, нарезки и обращения к модели."""

    # --- распознавание -------------------------------------------------
    #: Размер модели Whisper: ``tiny``…``large-v3``. По умолчанию самая
    #: крупная: на записи совещания она разбирает фамилии и цифры, на
    #: которых ``medium`` ошибается, а ошибка расшифровки въезжает прямо в
    #: поручение. Считает она примерно вдвое дольше и просит около 5 ГБ
    #: видеопамяти — не хватит, расчёт сам спустится на модель поменьше и
    #: скажет об этом.
    asr_model: str = "large-v3"
    language: str = "ru"
    #: Сколько участников говорит. Диаризация работает точнее, когда число
    #: известно: иначе она угадывает и склонна дробить одного на нескольких.
    speakers: int | None = None
    #: ``cuda``, ``cpu`` или ``auto``.
    device: str = "auto"
    batch_size: int = 8
    #: Не ходить в HuggingFace, если модели уже скачаны. Быстрее на повторных
    #: запусках и не отмечает лишний раз использование токена.
    offline_models: bool = False
    #: Свои слова распознаванию: фамилии участников, отраслевые термины,
    #: сокращения. Whisper принимает их подсказкой и заметно реже коверкает
    #: именно такие слова — а коверкает он их чаще всего, и ошибка въезжает
    #: прямо в текст поручения.
    #:
    #: Файл рядом с настройками: по слову в строке, или csv — тогда берётся
    #: первая колонка. Подсказка коротка по устройству самой модели, лишнее
    #: она отбрасывает, поэтому важное ставьте в начало файла.
    asr_hints_file: Path | None = None

    # --- нарезка -------------------------------------------------------
    #: Окно модели в токенах. Отсюда считается бюджет куска — нарезка нужна
    #: ровно потому, что стенограмма не влезает целиком. У модели с большим
    #: окном кусок получится один: часовое совещание это тысяч двадцать
    #: токенов, и при окне в миллион делить нечего.
    llm_context_tokens: int = 8192
    #: Бюджет куска в токенах. Пусто — считать от окна. Задавать вручную
    #: имеет смысл, чтобы сделать куски **меньше** расчётных: малая модель
    #: на длинном фрагменте начинает терять поручения из середины.
    chunk_max_tokens: int | None = None
    #: Какую долю окна отдать тексту. Остальное — промпту и ответу: если
    #: занять окно целиком, ответ обрежется на середине последнего поручения.
    chunk_context_share: float = 0.65
    #: Отбрасывать ли перекличку в начале записи перед отправкой в модель.
    #: На совещании с десятками подключений «как слышно, видно» занимает до
    #: половины записи и вытесняет из фрагментов настоящий разговор.
    #: Стенограммы это не касается: она сохраняется полной — расшифровка
    #: должна быть точной, а что войдёт в документ, решает тот, кто ведёт
    #: протокол.
    drop_soundcheck: bool = True
    #: Сколько реплик повторить в начале следующего куска.
    chunk_overlap_blocks: int = 1
    #: Показывать модели только фразы, в которых поручение слышно, вместе с
    #: соседними, — вместо сплошной нарезки всего совещания. На записи штаба
    #: это 101 окно по 97 токенов вместо семи кусков по 4700: втрое меньше
    #: текста, и терять середину длинного куска модели больше негде.
    extract_by_phrase: bool = True
    #: Переспрашивать ли модель по каждому найденному пункту: поручение это
    #: или изложение доклада. Правилами их уже не отделить — «отходы должны
    #: накапливаться раздельно» устроено как требование, — а коротким
    #: вопросом «да или нет» мелкая модель отвечает надёжно. Стоит одного
    #: запроса на пункт.
    verify_tasks: bool = True
    #: Сводить ли в один пункт поручения, сказанные одной фразой. «Передайте
    #: разговор, фотографии отправьте губернатору, усильте мониторинг» — три
    #: действия, но одно поручение: адресат один и срок один. Границей
    #: считается предложение, а расставляет точки распознавание, поэтому
    #: слишком длинное сведение отменяется само.
    one_task_per_phrase: bool = True

    # --- локальная модель ----------------------------------------------
    #: Адрес OpenAI-совместимого сервера: Ollama — 11434, LM Studio — 1234.
    llm_base_url: str = "http://localhost:11434/v1"
    llm_model: str = "mistral"
    #: Модель для проверочного прохода. Пусто — та же, что и для поручений.
    #:
    #: Задачи разные и требуют разного. Выписывать надо щедро: пропущенное
    #: поручение не видно никак, а лишнее вычёркивается за секунду. Проверять
    #: надо строго. На живой записи mistral нашёл 79% поручений против 39% у
    #: модели вчетверо крупнее — зато та ошибалась вдвое реже там, где
    #: отвечала. Отсюда и разделение: щедрая выписывает, строгая проверяет.
    #:
    #: Модели меняются в памяти один раз: проверка идёт после всей выписки.
    #: Первая перед этим выгружается, так что на карту нужен размер большей
    #: из двух, а не их сумма.
    llm_verify_model: str = ""
    #: Низкая температура намеренно: задача извлекающая, а не сочинительская.
    #: Поручение надо найти в тексте, а не придумать похожее.
    #:
    #: Касается только языковой модели — выписки и проверки. Распознавание
    #: речи ею не управляется: у Whisper своя, и он поднимает её сам, когда
    #: не может разобрать кусок.
    #:
    #: На время сравнений нужен ровно 0: при 0.1 два прогона одной
    #: стенограммы расходятся на пункт-другой, и это тот же порядок, что и
    #: разница между моделями.
    llm_temperature: float = 0.1
    #: Предел длины ответа. Тысячи не хватает: на плотном фрагменте модель
    #: выписывает десяток поручений и обрывается на полуслове, а оборванный
    #: JSON разбирается только частично.
    llm_max_tokens: int = 3000
    #: Местная модель отвечает медленно, особенно первый запрос после
    #: загрузки весов. Короткий таймаут здесь ломает работу чаще, чем спасает.
    #: Сводить ли поручения, сказанные разными словами. Правила снимают
    #: только буквальные повторы, а фрагменты пересекаются, и одно поручение
    #: приезжает дважды разными словами. Стоит одного лишнего запроса к
    #: модели; решает она при этом только «одно ли это и то же», а сливает
    #: записи код — придумать своё или потерять чужое она не может.
    merge_similar: bool = True
    #: Что добавить к указаниям модели. Дописывается в конец, к правилам
    #: формата не относится: их менять нельзя, иначе сломается разбор ответа,
    #: а человек не поймёт почему. Сюда идёт предметное — что считать
    #: поручением в вашей организации и как это называть.
    #:
    #: Например: «Поручения у нас называются заданиями» или «Не считай
    #: поручением просьбу выступить или подключиться».
    prompt_extra: str = ""
    #: Файл со своим системным указанием целиком, вместо встроенного. Для
    #: тех, кто понимает, что делает: правила формата придётся написать
    #: самому, иначе ответ не разберётся.
    prompt_file: Path | None = None
    #: То же для проверочного прохода — того, где по каждому найденному
    #: пункту спрашивают «поручение это или изложение доклада». Указания там
    #: нужны обратные: на выписке объясняют, что считать поручением, здесь —
    #: что поручением не считается, хотя звучит похоже.
    #:
    #: Например: «Планы работ, о которых докладывают, поручением не считай» —
    #: или, наоборот, «Просьбу выступить на следующем заседании считай».
    verify_prompt_extra: str = ""
    #: Просить ли у сервера строгий JSON. Для мелких моделей это решающая
    #: разница: уговорами формат от них не добиться, они просто продолжают
    #: текст, который видят. Сервер, который такого не умеет, ответит
    #: отказом, и запрос повторится без принуждения.
    llm_json_mode: bool = True
    llm_timeout_s: int = 180
    llm_retries: int = 2

    # --- пути ----------------------------------------------------------
    input_dir: Path = field(default_factory=lambda: Path("data/input"))
    output_dir: Path = field(default_factory=lambda: Path("data/output"))
    #: Промежуточное: извлечённый звук и результаты шагов. Здесь и копятся
    #: гигабайты — двухчасовая запись даёт около 230 МБ одного только wav.
    work_dir: Path = field(default_factory=lambda: Path("data/work"))
    #: Оставлять ли промежуточное после готового протокола. По умолчанию нет:
    #: гигабайты копятся незаметно, а нужны они редко.
    keep_work_files: bool = False

    # --- направления ---------------------------------------------------
    #: Справочник того, по кому идёт разбор: регионы, филиалы, площадки,
    #: направления работ — что перебирают на вашем совещании. Файл рядом с
    #: настройками, две колонки: как называть и как это звучит в речи.
    #:
    #: Пусто — графа останется пустой. Выдумывать в неё нечего: услышанное
    #: название инструмент не берёт, потому что распознавание их коверкает,
    #: а неверный адресат хуже пустого.
    directory_file: Path | None = None
    #: Свои слова: чем поручают именно у вас и что у вас поручением не
    #: считается. Файл в две колонки, разделы «поручают» и «не поручают».
    #: Дополняет встроенный список, а не заменяет.
    words_file: Path | None = None
    #: Как называть эту графу в протоколе и в таблице поручений. У штаба
    #: это «Регион», у завода «Площадка», у холдинга «Общество».
    directory_label: str = "Направление"
    #: Дописывать ли формулировки по окну. Выписывая, модель отдаёт ядро —
    #: «обеспечить связь», — а в документе такой пункт нельзя ни исполнить,
    #: ни проверить: предмет и подробности стоят в соседних фразах окна.
    #: Стоит одного запроса на пункт, как и проверка.
    rewrite_tasks: bool = True
    #: Оборот, которым поручают: «Рекомендовать», «Поручить», «Предложить».
    #: Один на всю организацию, поэтому живёт здесь, а не в справочнике: там
    #: у каждой строки своё — падеж, который зависит от названия.
    #:
    #: Место адресата обозначается ``{кому}``; без него оборот ставится
    #: перед адресатом. Применяется только к адресатам из справочника: у них
    #: дательный падеж выверен рукой, а «Рекомендовать все регионы» —
    #: не по-русски.
    decision_formula: str = ""
    #: Писать ли в имя прогона модели, которыми считали. Пока набор
    #: подбирают — это главное, чем прогоны различаются: ту же запись гоняют
    #: с разной проверочной моделью и сравнивают числа. Когда устоится,
    #: превратится в шум, и это выключают.
    name_with_models: bool = True
    #: Форма протокола: файл с местами вида ``{{date}}`` и ``{{decisions}}``.
    #: Форма документа в каждой организации своя — с гербом, номером, грифом
    #: и своими разделами, — и угадать её снаружи нельзя. Пусто — документ
    #: собирается по встроенной разметке: она годится для работы, но не для
    #: рассылки за подписью.
    form_file: Path | None = None

    #: Заголовок в шапке приложения и на вкладке браузера. В организации у
    #: инструмента бывает своё имя, и «minuteforge» ей ничего не говорит.
    app_title: str = "minuteforge"
    log_dir: Path = field(default_factory=lambda: Path("logs"))
    log_level: str = "INFO"

    @property
    def chunk_budget(self) -> int:
        """Сколько токенов стенограммы уходит в один запрос."""
        if self.chunk_max_tokens:
            return int(self.chunk_max_tokens)
        return max(500, int(self.llm_context_tokens * self.chunk_context_share))

    @property
    def hf_token(self) -> str | None:
        """Токен HuggingFace — только из окружения.

        Свойством, а не полем: поле попало бы в ``asdict`` и утекло бы в
        журнал или в сохранённые настройки вместе со всем остальным.
        """
        return os.environ.get(HF_TOKEN_ENV) or None

    @property
    def llm_key(self) -> str | None:
        """Ключ к внешней модели — только из окружения.

        Локальному серверу ключ не нужен, и обычно его тут нет. Он появляется
        у тех, кто сознательно подключил внешнюю модель, и хранить его в
        файле настроек нельзя ровно по той же причине, что и токен
        HuggingFace: файл настроек показывают, пересылают и кладут в
        репозиторий.
        """
        return os.environ.get(LLM_KEY_ENV) or None

    @classmethod
    def load(cls, path: str | Path | None = None) -> "Settings":
        """Собирает настройки из файла и окружения.

        Свой ``config.yaml`` в репозитории не лежит: его правят под своё
        место работы — пути к папкам, адрес сервера, — и обновление
        приложения такие правки затирало бы конфликтом. В репозитории лежит
        только образец, а он берётся, пока своего файла нет.
        """
        values: dict[str, Any] = {}
        path = Path(path) if path else _config_path()
        if path.exists() and yaml is not None:
            loaded = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
            values.update({k: v for k, v in loaded.items() if k in _names()})

        for name, kind in _kinds().items():
            raw = os.environ.get(f"MINUTEFORGE_{name.upper()}")
            if raw is not None:
                values[name] = _cast(raw, kind)

        return cls(**values)

    def to_dict(self) -> dict[str, Any]:
        """Настройки для журнала. Секретов здесь нет и быть не должно."""
        return {k: str(v) if isinstance(v, Path) else v for k, v in asdict(self).items()}


#: Файл настроек и образец, из которого его делают.
CONFIG_FILE = "config.yaml"
CONFIG_EXAMPLE = "config.example.yaml"


def _config_path() -> Path:
    """Свой файл, а нет своего — образец из репозитория."""
    own = Path(CONFIG_FILE)
    return own if own.exists() else Path(CONFIG_EXAMPLE)


def _names() -> set[str]:
    return {f.name for f in fields(Settings)}


def _kinds() -> dict[str, Any]:
    return {f.name: f.type for f in fields(Settings)}


def _cast(raw: str, kind: Any) -> Any:
    text = str(kind)
    if "Path" in text:
        return Path(raw)
    if "bool" in text:
        return raw.strip().lower() in {"1", "true", "yes", "да"}
    if "int" in text:
        return int(raw)
    if "float" in text:
        return float(raw)
    return raw
