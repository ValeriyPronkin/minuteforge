def clean_due(due: str) -> str:
    """Оставляет срок, только если это похоже на срок.

    Модель охотно заполняет это поле состоянием («Завершена», «В процессе»)
    или обрывком реплики («Добрый день»). В таблице контроля такое хуже
    пустого: строка выглядит заполненной, а спросить по ней нечего.
    """
    due = (due or "").strip()
    if not due or not is_russian(due):
        return ""
    if len(due.split()) > 8:
        # Срок — это «до пятницы» или «15 сентября», а не абзац. Модель
        # кладёт сюда кусок доклада, и в таблице контроля он занимает три
        # строки, ничего при этом не сообщая.
        return ""
    lowered = due.lower()
    if any(ch.isdigit() for ch in lowered):
        return due
    return due if any(mark in lowered for mark in _LOOKS_LIKE_DUE) else ""


def _significant(text: str) -> set[str]:
    """Слова, по которым можно узнать, о том ли речь.

    Короткие отбрасываются: «в», «на», «для» есть в любом тексте и ничего не
    доказывают. Берётся начало слова, чтобы падежи не мешали: «поручение» и
    «поручения» — одно и то же.
    """
    return {word[:6] for word in re.findall(r"\w{5,}", (text or "").lower())}


def grounded(task: Task, source: str) -> bool:
    """Опирается ли поручение на текст, из которого взято.

    Это и есть проверка на выдумку. Модель, потерявшая нить, сочиняет
    правдоподобные поручения из ничего — «Analyze the presentation,
    исполнитель Assistant, срок 2022-08-15» — и отличить их от настоящих
    можно ровно одним способом: посмотреть, есть ли эти слова в стенограмме.

    Порог невысокий: модель имеет право переформулировать, и требовать
    дословности значило бы выбрасывать хорошие поручения.
    """
    words = _significant(task.what)
    if not words:
        return False
    found = words & _significant(source)
    return len(found) / len(words) >= 0.3


def clean_assignee(who: str, source: str) -> str:
    """Оставляет исполнителя, только если он в стенограмме и похож на имя.

    Модель кладёт в это поле целые предложения — «The team should analyze
    the current status…» — и выдумывает адресатов, которых на совещании не
    было. Ни то, ни другое в графу «Исполнитель» не годится.
    """
    who = (who or "").strip()
    if not who:
        return ""
    plain = who.lower().strip(".,")
    if plain in _NOT_AN_ASSIGNEE:
        return ""
    if plain in COLLECTIVE:
        # Круг исполнителей назван, пусть и общим словом. Проверять его по
        # стенограмме незачем: это не фамилия, выдумать его модели негде.
        return COLLECTIVE[plain]
    if len(who.split()) > 6:
        return ""  # это предложение, а не исполнитель
    if not is_russian(who):
        return ""
    known = _significant(source)
    words = _significant(who)
    if words and not (words & known):
        return ""  # такого на совещании не называли
    return who


#: С чего фраза начинается прежде обращения: «Так, коллеги…», «И, Андрей
#: Николаевич, прошу…». Присказку пропускаем, обращение ищем за ней.
_BEFORE_ADDRESS = frozenset("""
и а ну так вот но да значит поэтому пожалуйста хорошо тогда сейчас теперь
уважаемые уважаемый уважаемая коллега
""".split())

#: Обращение по имени-отчеству: «Сергей Анатольевич, подготовьте».
_BY_PATRONYMIC = re.compile(
    r"^([А-ЯЁ][а-яё]{2,})\s+([А-ЯЁ][а-яё]+(?:ович|евич|овна|евна|ична))\b"
)

#: Обращение к региону: «Коллеги Ростовской области, просьба подтвердить»,
#: «Ставропольский край, начинайте». Так на штабе обращаются чаще, чем по
#: фамилии: за регион отвечает не человек, а администрация.
_BY_REGION = re.compile(
    r"^(?:коллеги\s+|администрация\s+|город\s+)?"
    r"([А-ЯЁ][а-яё]+(?:ой|ая|ий|ый|ая)?\s+"
    r"(?:области|область|края|край|республики|республика|округа|округ))\b",
    re.IGNORECASE,
)

#: Обращение по имени с фамилией: «Светлана Дина, просьба обозначить срок».
#: Первое слово проверяется по святцам — иначе «Принято, продолжаем» тоже
#: сойдёт за обращение.
_BY_GIVEN_NAME = re.compile(r"^([А-ЯЁ][а-яё]{2,})(?:\s+([А-ЯЁ][а-яё]{2,}))?\s*,")

#: Обращение к залу целиком: «Коллеги, обеспечьте вывоз».
_BY_ROOM = re.compile(r"^(коллеги|уважаемые\s+коллеги|регионы|субъекты)\b", re.IGNORECASE)


def addressee(sentence: str) -> str:
    """Кому сказано — по обращению в начале фразы.

    Поручение почти всегда открывается адресатом: «Светлана Дина, просьба
    обозначить срок», «Коллеги Ростовской области, прошу подтвердить»,
    «Ессентуки, дайте оценку». Модель это поле почти не заполняет — из
    семидесяти двух поручений исполнитель стоял у шестнадцати, — а в самой
    реплике адресат назван, и брать его оттуда правилам по силам.

    Ищется только в начале фразы, и это намеренно: имя, названное в
    середине, чаще всего принадлежит не тому, кому поручают, а тому, о ком
    говорят. Неверный адресат хуже пустого — пустой заставляет уточнить
    перед рассылкой, неверный уходит в рассылку как есть.
    """
    head = _without_filler(sentence)
    if not head:
        return ""
    by_name = _BY_PATRONYMIC.match(head)
    if by_name:
        return f"{by_name.group(1)} {by_name.group(2)}"
    by_region = _BY_REGION.match(head)
    if by_region:
        return " ".join(by_region.group(1).split())
    by_room = _BY_ROOM.match(head)
    if by_room:
        return COLLECTIVE.get(by_room.group(1).lower(), "")
    by_given = _BY_GIVEN_NAME.match(head)
    if by_given and is_given_name(by_given.group(1).lower()):
        return " ".join(part for part in by_given.groups() if part)
    return ""


def _without_filler(sentence: str) -> str:
    """Отрезает присказку перед обращением, не трогая самого обращения."""
    words = (sentence or "").strip().split()
    while words and words[0].strip(",.!?…").lower() in _BEFORE_ADDRESS:
        # «Коллеги Ростовской области» — обращение, а не присказка: слово
        # уходит, только если за ним запятая или ещё одна присказка.
        if words[0].strip(",.!?…").lower() in ("уважаемые", "уважаемый", "коллега"):
            words = words[1:]
            continue
        if not words[0].endswith((",", ".", "!", "?", "…")):
            break
        words = words[1:]
    return " ".join(words)


#: Насколько должны совпасть имя и отчество, чтобы это был один человек.
#: Пороги разные и считаются порознь — целиком строки сравнивать нельзя:
#: «Андрей Николаевич» и «Антон Николаевич» совпадают на 0,79, а «Джамбулат
#: Хизирович» и «Шамбулат Кириллович» — на 0,74, хотя первые двое разные
#: люди, а вторые один и тот же, услышанный дважды по-разному. Различает их
#: имя: 0,36 против 0,82.
SAME_GIVEN_NAME = 0.7
SAME_PATRONYMIC = 0.6


def same_person(one: str, other: str) -> bool:
    """Один ли это человек, названный дважды по-разному.

    Распознавание коверкает имена так, что один ведущий приезжает четырьмя
    людьми: «Джамбулат Хизирович», «Жабулат Хизирович», «Шамбулат
    Кириллович», «Джамбулат Кизирович». Считать их разными — значит не
    узнать ведущего ни в одном из написаний.
    """
    left, right = (one or "").lower().split(), (other or "").lower().split()
    if not left or not right:
        return False
    if len(left) < 2 or len(right) < 2:
        return SequenceMatcher(None, " ".join(left), " ".join(right)).ratio() >= 0.85
    return (
        SequenceMatcher(None, left[0], right[0]).ratio() >= SAME_GIVEN_NAME
        and SequenceMatcher(None, left[1], right[1]).ratio() >= SAME_PATRONYMIC
    )


#: Сколько раз должны обратиться к человеку, чтобы счесть его ведущим.
#: Ведущего окликают весь штаб — «Джамбулат Хизирович, разрешите», — а
#: случайное обращение звучит один раз.
CHAIR_MENTIONS = 3


def most_addressed(blocks: Sequence[object]) -> str:
    """К кому обращаются чаще всех — тот и ведёт совещание.

    Нужно, чтобы не записать его в исполнители. Докладчик начинает свою
    речь обращением к ведущему — «Жабулат Хизирович, ранее отмечали…», — а
    поручение внутри этой же реплики адресовано вовсе не ему. В протоколе
    выходило, что ведущий поручил работу сам себе.
    """
    counted: dict[str, int] = {}
    for block in blocks:
        for sentence in _sentences(getattr(block, "text", "") or ""):
            name = addressee(sentence)
            # Обращение к залу ведущим не бывает.
            if not name or name in COLLECTIVE_NAMES:
                continue
            # Написания сводятся: иначе четыре версии одного имени наберут
            # по одному упоминанию и ведущего не опознает никто.
            same = next((known for known in counted if same_person(known, name)), name)
            counted[same] = counted.get(same, 0) + 1
    if not counted:
        return ""
    name, times = max(counted.items(), key=lambda item: item[1])
    return name if times >= CHAIR_MENTIONS else ""


def with_addressee(tasks: Sequence[Task], *, chair: str = "") -> list[Task]:
    """Дописывает исполнителя из обращения там, где модель его не назвала.

    Своё модель не переписывает: сказанное ею проверено по стенограмме и
    точнее — она видит всю фразу, а правило только её начало.

    :param chair: кто ведёт совещание. Ему поручений не дают: обращение к
        нему открывает доклад, а не поручение.
    """
    filled = []
    for task in tasks:
        if task.who or not task.quote:
            filled.append(task)
            continue
        # Ищем и в цитате, и в куске: обращение бывает фразой раньше —
        # «Коллеги Ростовской области. Просьба подтвердить срок ввода».
        found = addressee(task.quote) or addressee(task.context)
        if found and chair and same_person(found, chair):
            found = ""
        filled.append(replace(task, who=found) if found else task)
    return filled


#: Как срок звучит на совещании. Порядок важен: сперва то, что длиннее и
#: определённее — «до конца года», «на 30 ноября», — иначе «до конца» съест
#: короткое «до».
_SPOKEN_DUE = re.compile(
    r"(?:"
    r"до\s+конца\s+(?:года|месяца|недели|квартала)"
    r"|(?:до|к|на|в)\s+\d{1,2}\s+(?:январ|феврал|март|апрел|ма[йя]|июн|июл|"
    r"август|сентябр|октябр|ноябр|декабр)\w*"
    r"|(?:до|к|на)\s+\d{1,2}[.\-/]\d{1,2}(?:[.\-/]\d{2,4})?"
    # После «через» единица времени обязательна: «через дорогу от сквера»
    # разбиралось как срок, и пункт получал графу «Срок: через дорогу».
    # Либо число с единицей — «через две недели», — либо единица сама:
    # «через месяц».
    r"|(?:через|в\s+течение|в\s+течении)\s+(?:ближайш\w+\s+)?(?:"
    r"(?:\d+|[а-яё]+)\s+(?:недел\w*|дн\w*|день|дней|месяц\w*|час\w*|год\w*|квартал\w*)"
    r"|(?:недел\w+|дн\w+|день|месяц\w*|час\w*|год\w*|квартал\w*)"
    r")"
    r"|(?:до|к|в)\s+(?:понедельник\w*|вторник\w*|сред[ыуе]|четверг\w*|"
    r"пятниц\w*|суббот\w*|воскресен\w*)"
    r"|сегодня(?:\s+же)?|завтра|послезавтра"
    r"|еженедельно|ежемесячно|ежедневно|ежеквартально|постоянно"
    r"|немедленно|срочно"
    r")",
    re.IGNORECASE,
)


#: После этих слов дата — не срок, а ссылка на прошлое: «по информации на
#: 2 сентября строительная готовность 84%». Сроком назад не назначают.
_ABOUT_THE_PAST = ("по информации", "по данным", "по состоянию", "на момент")

#: «Сегодня» и «сейчас» — единственные слова из списка сроков, которые в
#: русском чаще наречия, чем сроки: «показатели сегодня», «сегодня было
#: удивительно», «стандарт, который сегодня будет в стране». Отличить их от
#: срока нельзя, зато можно требовать, чтобы они стояли в самой фразе
#: поручения: «отошлите прям сегодня же» — срок, «сегодня» из соседнего
#: предложения — почти всегда наречие.
_ADVERB_LIKE = ("сегодня", "сейчас", "текущ")

#: Порядок работы, а не день: «докладывать еженедельно». Сроком это
#: остаётся, но поручением фразу не делает — в докладах «ежедневно
#: мониторим» звучит постоянно.
_CADENCE = ("еженедельно", "ежемесячно", "ежедневно", "ежеквартально", "постоянно")


def firm_due(text: str) -> str:
    """Срок, который сам по себе выдаёт поручение.

    То же, что :func:`spoken_due`, но без «сегодня» и «сейчас»: по ним
    отбирать нельзя, иначе в отбор попадёт каждая вторая фраза доклада.
    """
    due = spoken_due(text)
    return "" if any(word in due.lower() for word in _ADVERB_LIKE) else due


def due_point(text: str) -> str:
    """Названный день, к которому надо успеть.

    От :func:`firm_due` отличается тем, что порядок работы сроком-точкой не
    считается: «мониторинг производится ежедневно» — это описание, а «через
    неделю на доклад замгубернатора» — поручение, хотя глагола в нём нет.
    """
    due = firm_due(text)
    return "" if any(word in due.lower() for word in _CADENCE) else due


def spoken_due(text: str) -> str:
    """Срок, как он прозвучал в реплике.

    Модель это поле почти не заполняет — на записи штаба срок стоял у
    одного поручения из сорока, хотя вслух звучал у доброго десятка:
    «через две недели», «до конца года», «сегодня же», «на 30 ноября».
    Правилу это по силам, как и адресату.
    """
    text = text or ""
    for found in _SPOKEN_DUE.finditer(text):
        before = text[max(0, found.start() - 40):found.start()].lower()
        if any(word in before for word in _ABOUT_THE_PAST):
            continue
        return " ".join(found.group(0).split())
    return ""


def with_due(tasks: Sequence[Task]) -> list[Task]:
    """Дописывает срок из реплики там, где модель его не назвала.

    Своё модель не переписывает. Сперва ищем в самой фразе поручения, потом
    в соседних: «Подготовьте справку. До среды» — обычный способ назначить
    срок, и во второй фразе он и стоит.

    Из соседних фраз «сегодня» и «сейчас» не берутся. Они там почти всегда
    наречия — «стандарт, который сегодня будет в стране», «было сегодня
    удивительно», — и пункт получал сроком день совещания, которого никто не
    назначал. В своей фразе они остаются сроком: «отошлите прям сегодня же».
    """
    filled = []
    for task in tasks:
        if task.due or not task.quote:
            filled.append(task)
            continue
        found = spoken_due(task.quote) or firm_due(task.context)
        filled.append(replace(task, due=clean_due(found)) if found else task)
    return filled


#: Слова, которыми на совещании поручают. Список закрытый и составлен по
#: живым записям: повелительное наклонение по-русски не отличить от
#: изъявительного одним правилом — «покажите» и «видите» устроены одинаково,
#: и морфологии для различения нет. Зато перечислить то, чем в самом деле
#: поручают, можно.
DIRECTIVE_WORDS = frozenset("""
прошу просим просил просила просьба поручаю поручить поручено поручается
требую требуем требуется настоятельно необходимо нужно нужен нужна нужны надо
должен должна должны должно обязан обязаны предстоит
ждём ждем давайте пожалуйста

предлагаю предлагаем предлагается поручаем рекомендую рекомендуем

обеспечьте подготовьте направьте доложите доложить представьте примите
проверьте проконтролируйте организуйте пригласите назовите подтвердите
уточните уточнитесь разберитесь передайте отправьте отошлите покажите
сделайте завершите завершайте ускорьте усильте усильтесь вынесите вынесете
проведите обратите зафиксируйте свяжитесь проработайте включитесь выполните
начните займитесь доработайте рассмотрите изучите учтите выделите закупите
приобретите исправьте устраните берите езжайте побывайте разошлите
""".split())

#: Присказка, а не поручение. «Да, смотрите, я им пока покажу», «давайте
#: сэкономим время» — этим ничего не поручают, а по правилу они проходили
#: наравне с «направьте» и давали в протоколе «Показать прессу» и
#: «Экономить время». Слово-обращение к вниманию, не к работе.
_FILLER_DIRECTIVES = frozenset("смотрите давайте".split())

#: Повелительное наклонение на «-йте» безопасно опознаётся по окончанию:
#: изъявительные формы так почти не кончаются. «Организуйте», «зафиксируйте»,
#: «направляйте» — и ни одного «видите» в придачу.
#:
#: «-йтесь» — то же самое у возвратных глаголов: «постарайтесь»,
#: «занимайтесь», «разбирайтесь». Без него «Постарайтесь в ноябре все
#: завершить» поручением не считалось: окончание другое. Изъявительных форм
#: на «-йтесь» в русском нет — там «-етесь» и «-итесь», — так что риска тот
#: же, что и с «-йте».
_IMPERATIVE_TAIL = ("йте", "йтесь")

#: Кроме приветствий: они устроены точно так же. «Здравствуйте, как слышно?»
#: кончается на «-йте» неотличимо от «зафиксируйте», и на записи штаба, где
#: подключаются тридцать регионов, таких реплик полторы сотни — половина
#: стенограммы. Ни одна из них ничего не поручает.
_NOT_A_DIRECTIVE_TAIL = frozenset("""
здравствуйте извините простите подскажите послушайте подождите погодите
смотрите давайте
""".split())

#: Прошедшее время сразу за словом требования переводит его в упрёк.
_PAST = frozenset("был была были было".split())

#: Слова, с которых начинается рассуждение, а не поручение.
_IF = frozenset("если когда раз".split())

#: Чем рассуждение открывается на слух: «Ну если надо…», «Вот если надо…».
_FILLER = frozenset("ну и а вот но да так значит поэтому".split())

#: Требования, которые внутри «если» ничего не поручают: «Если надо собрать
#: всех участников — значит, это надо делать» сказано о работе вообще, а не
#: кому-то и не к сроку. Настоящее поручение внутри условия звучит иначе —
#: «если будут вопросы, прошу доложить», — и «прошу» его выдаёт.
_WEAK_INSIDE_IF = frozenset("надо нужно необходимо должен должна должны должно".split())

#: Ведение совещания: перейти к вопросу, заслушать регион, дать слово. Это
#: распорядок, а не работа, и в таблице контроля ему делать нечего.
_AGENDA_VERBS = frozenset("""
рассмотреть рассмотрению перейти переходим заслушать заслушивать послушать
вызывать вызвать доложить
""".split())


def _conditional(words: list[str]) -> bool:
    """Рассуждение «если надо — значит, надо делать», а не поручение."""
    head = [word for word in words[:3] if word not in _FILLER]
    if not head or head[0] not in _IF:
        return False
    return not any(
        word in DIRECTIVE_WORDS and word not in _WEAK_INSIDE_IF for word in words
    )


def _agenda(words: list[str]) -> bool:
    """Распорядок совещания: «предлагается рассмотреть», «предлагаю перейти».

    Слово «предлагаю» одинаково открывает и распорядок, и настоящее
    поручение, поэтому одного его мало. Отличает второе требование рядом:
    «предлагаю перейти к вопросу и прошу подготовить справку» — поручение, а
    «предлагается рассмотреть Пермский край» — повестка.
    """
    if not any(word.startswith("предлага") for word in words):
        return False
    if not set(words) & _AGENDA_VERBS:
        return False
    return not any(
        word in DIRECTIVE_WORDS and not word.startswith("предлага") for word in words
    )


def is_directive(sentence: str) -> bool:
    """Поручают ли этой фразой — или просто рассказывают.

    Главный источник мусора в протоколе не выдуманные поручения, а
    настоящие фразы, переписанные в повелительном наклонении: «Видим
    показатели мощности» превращается в «Проанализировать показатели
    мощности», «Вот эта техника стоит третий год» — в «Подтвердить или
    опровергнуть, что техника стоит третий год». Ни того, ни другого никто
    не поручал, а в таблице контроля они неотличимы от настоящего пункта.

    Поэтому поручение оставляется, только если поручение слышно в самой
    реплике: есть слово требования или глагол в повелительном наклонении.
    """
    words = re.findall(r"\w+", (sentence or "").lower())
    if _conditional(words) or _agenda(words):
        return False
    for position, word in enumerate(words):
        if word not in DIRECTIVE_WORDS or word in _FILLER_DIRECTIVES:
            continue
        # «Должен был принять и рассчитаться» — упрёк за несделанное, а не
        # поручение сделать. В прошедшем времени поручений не дают.
        if words[position + 1:position + 2] and words[position + 1] in _PAST:
            continue
        return True
    return any(
        len(word) > 4
        and word.endswith(_IMPERATIVE_TAIL)
        and word not in _NOT_A_DIRECTIVE_TAIL
        for word in words
    )


#: Вежливость. Сама по себе она ничего не поручает: «подскажите,
#: пожалуйста» и «просьба» одинаково открывают и поручение, и перекличку.
#: Отличать их приходится по тому, что стоит рядом.
_POLITENESS = frozenset("""
пожалуйста просьба прошу просим просил просила подскажите скажите давайте
""".split())

#: Чем перекличка просит отозваться. Внутри «как слышно, видно» это про
#: связь, а не про работу: «Красноярский край видно, слышно, подтвердите?» —
#: и в протоколе стоял пункт «Подтвердить», исполнитель Павленко.
#: Вне переклички те же слова поручают, поэтому список действует только там.
_ABOUT_THE_LINK = frozenset("""
подтвердите поттвердите подтвердить повторите проверьте включите выключите
отзовитесь
""".split())


def asks_for_work(text: str) -> bool:
    """Поручение ли это, если не считать вежливости.

    Нужно там, где вежливых слов не хватает для решения: внутри переклички.
    «Подскажите, пожалуйста, Республику Калмыкию слышно, видно?» устроено
    как поручение — есть и «подскажите», и «пожалуйста», — но поручено этим
    ничего. А «Слышно. Иванов, подготовьте справку» поручает, и отличает
    его глагол, который вежливостью не является.
    """
    words = re.findall(r"\w+", (text or "").lower())
    if not is_directive(text):
        return False
    empty = _POLITENESS | _ABOUT_THE_LINK
    if any(word in DIRECTIVE_WORDS and word not in empty for word in words):
        return True
    return any(
        len(word) > 4
        and word.endswith(_IMPERATIVE_TAIL)
        and word not in _NOT_A_DIRECTIVE_TAIL
        and word not in empty
        for word in words
    )


def worth_showing(sentence: str) -> bool:
    """Стоит ли показывать эту фразу модели.

    Так отбираются окна: модель читает не всё совещание, а фразы, в которых
    поручение слышно, вместе с соседними.

    Перекличка разбирается отдельно. Реплику целиком она отсеивается не
    всегда: «Это вот шестая. Сейчас, да, смотрите… Подскажите, видно, да?» —
    длинная, под правило о перекличке не попадает, а поручения в ней нет.
    Пофразно попадает, и тогда решает :func:`asks_for_work`: «подскажите,
    видно?» отпадает, «слышно, Иванов, подготовьте справку» остаётся.
    """
    if is_soundcheck(sentence):
        return asks_for_work(sentence)
    # Названный срок показывает фразу модели, даже если поручения в ней не
    # слышно. Поручение сплошь и рядом стоит без глагола — «и через неделю
    # на доклад замгубернатора», «неделя вам на организацию доклада», — и
    # правилом такое не берётся, а срок в нём назван прямо.
    return is_directive(sentence) or bool(firm_due(sentence))


#: Сколько значащих слов должно быть в поручении. Одного не бывает:
#: «Подтвердить» — это не задание, а обломок фразы «Просьба подтвердить».
#: Что подтвердить, кому и к какому сроку — в таком пункте не сказано, и в
#: таблице контроля с него нечего спросить.
MEANINGFUL_WORDS = 2


def keep_meaningful(tasks: Iterable[Task]) -> list[Task]:
    """Выбрасывает поручения из одного слова.

    Мелкая модель, увидев «Просьба подтверждить» без продолжения, честно
    выписывает «Подтвердить» — и формально она права, поручение прозвучало.
    Но пункт из одного слова нельзя ни разослать, ни проверить: глагол без
    предмета не задание.
    """
    return [
        task for task in tasks
        if len(re.findall(r"\w{3,}", task.what or "")) >= MEANINGFUL_WORDS
    ]


def keep_directives(tasks: Iterable[Task]) -> list[Task]:
    """Оставляет поручения, которые слышны в реплике-источнике.

    Поручение без источника не выбрасывается: проверить его нечем, но и
    оснований не верить модели нет.

    Фраза с названным днём остаётся, даже если поручения в ней не слышно:
    «и через неделю на доклад замгубернатора» — поручение без глагола, и
    отсеять его значило бы потерять единственный пункт со сроком. Порядок
    работы в это не входит: «мониторинг производится ежедневно» — описание,
    а не задание.
    """
    return [
        task for task in tasks
        if not task.quote or is_directive(task.quote) or due_point(task.quote)
    ]


#: Насколько два поручения из одной реплики должны пересечься словами,
#: чтобы считаться одним. Порог ниже, чем у :data:`SAME_TASK`: там сравнение
#: идёт между разными местами записи, здесь — внутри одной фразы, и
#: случайно совпасть им негде.
SAME_PLACE = 0.4


def one_per_place(tasks: Sequence[Task]) -> list[Task]:
    """Из нескольких поручений, выписанных из одной реплики, оставляет одно.

    Модель разбирает стенограмму по фрагментам с нахлёстом и одну и ту же
    фразу выписывает дважды разными словами: «Отправить фотографии и
    подробный отчёт губернатору» и «Отправить фотографии отчёта губернатору
    и усиленному мониторингу всех муниципальных образований». Для
    делопроизводителя это один пункт, и увидев два, он вычеркнет оба.

    Оставляется более полное: с исполнителем, а при прочих равных — то, где
    поручение сформулировано подробнее.
    """
    kept: list[Task] = []
    for task in _without_scraps(tasks):
        words = _significant(task.what)
        twin = None
        for other in kept:
            if _normalize(other.quote) != _normalize(task.quote) or not other.quote:
                continue
            shared = words & _significant(other.what)
            if shared and len(shared) / max(1, min(len(words), len(_significant(other.what)))) >= SAME_PLACE:
                twin = other
                break
        if twin is None:
            kept.append(task)
            continue
        if _fuller(task, twin):
            kept[kept.index(twin)] = task
    return kept


#: Короче этого поручение не живёт своей жизнью: одно значащее слово рядом с
#: полным пунктом из той же фразы — обломок, а не поручение.
#:
#: Порог намеренно низкий. В одной фразе поручений бывает три — «обновлять
#: контейнерный парк, завершать создание площадок и обеспечивать вывоз», — и
#: короткое третье ничем не хуже длинного первого. Лишний пункт вычеркнут
#: при вычитке, потерянный не восстановит никто.
SCRAP_WORDS = 1


def _without_scraps(tasks: Sequence[Task]) -> list[Task]:
    """Выбрасывает обрывки, если из той же реплики выписано что-то полнее."""
    kept = []
    for task in tasks:
        if len(_significant(task.what)) > SCRAP_WORDS:
            kept.append(task)
            continue
        fuller_nearby = any(
            other is not task
            and other.quote
            and _normalize(other.quote) == _normalize(task.quote)
            and len(_significant(other.what)) > SCRAP_WORDS
            for other in tasks
        )
        if not fuller_nearby:
            kept.append(task)
    return kept


#: Длиннее этого сведённый пункт не читается. Ограничение нужно не ради
#: красоты: «одна фраза» у нас решается по точкам, которые расставило
#: распознавание, а оно их иногда не ставит вовсе. Там, где две минуты речи
#: приехали одним предложением, сведение дало бы пункт, по которому нельзя
#: спросить. В таком случае лучше оставить как было — раздельно.
ONE_PHRASE_LIMIT = 300


def one_per_phrase(tasks: Sequence[Task]) -> list[Task]:
    """Сводит в один пункт поручения, сказанные одной фразой.

    «Передайте разговор, все фотографии отправьте губернатору с подробным
    отчётом, кратно усиленным мониторингом всех муниципальных образований» —
    это три действия, но одно поручение: адресат один, срок один, и в
    таблице контроля тремя строками оно только запутает.

    Отличается от :func:`one_per_place` тем, что там из похожих оставляли
    одно, а здесь разные складываются вместе: ни одно действие не теряется.
    """
    order: list[str] = []
    groups: dict[str, list[Task]] = {}
    for task in tasks:
        key = _normalize(task.quote) if task.quote else f"без цитаты {len(order)}"
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append(task)

    kept: list[Task] = []
    for key in order:
        group = groups[key]
        if len(group) == 1:
            kept.append(group[0])
            continue
        joined = _join_actions(group)
        if len(joined) > ONE_PHRASE_LIMIT:
            # Фраза оказалась не фразой, а абзацем без точек. Разбирать её
            # мы не умеем, поэтому оставляем как было.
            kept.extend(group)
            continue
        kept.append(replace(
            group[0],
            what=joined,
            who=next((t.who for t in group if t.who), ""),
            due=next((t.due for t in group if t.due), ""),
            region=next((t.region for t in group if t.region), ""),
            at=next((t.at for t in group if t.at is not None), None),
        ))
    return kept


def _join_actions(group: Sequence[Task]) -> str:
    """Складывает действия одной фразы в один пункт.

    Повторы отбрасываются: модель выписывает одно и то же действие дважды
    разными словами, и в сведённом пункте это видно сразу.
    """
    parts: list[str] = []
    for task in group:
        what = (task.what or "").strip().rstrip(".")
        if not what:
            continue
        words = _significant(what)
        if any(words and words <= _significant(part) for part in parts):
            continue
        parts.append(what)
    if not parts:
        return ""
    tail = [_lowered(part) for part in parts[1:]]
    return "; ".join([parts[0], *tail])


def _lowered(text: str) -> str:
    """Со строчной — кроме сокращений вроде ППК, которые пишутся прописными."""
    first = text.split(" ", 1)[0]
    if len(first) > 1 and first.isupper():
        return text
    return text[0].lower() + text[1:]


def _fuller(task: Task, other: Task) -> bool:
    """Какое из двух поручений полнее — то и остаётся в протоколе."""
    if bool(task.who) != bool(other.who):
        return bool(task.who)
    return len(task.what) > len(other.what)


def extract_tasks(
    chunks: Sequence[Chunk],
    client: LLMClient,
    *,
    skip_failed: bool = True,
    progress: Progress | None = None,
    answers: list[str] | None = None,
    corpus: str | None = None,
    chair: str = "",
    journal=None,
) -> list[Task]:
    """Проходит по кускам стенограммы и собирает поручения.

    :param skip_failed: что делать, если модель не ответила на кусок. По
        умолчанию — пропустить и идти дальше: терять весь час работы из-за
        одного сбоя хуже, чем недосчитаться поручений из одного фрагмента.
        Пропуск пишется в журнал, молча это не проходит.
    :param progress: куда сообщать о ходе. Местная модель отвечает по
        десятку секунд на фрагмент, и на длинном совещании это минуты
        тишины, за которые человек успевает решить, что всё повисло.
    :param corpus: вся стенограмма целиком — по ней проверяются исполнители.
        Человека называют один раз, в начале совещания, а поручение он
        получает часом позже, в другом фрагменте; сверяться только с
        фрагментом значило бы вычёркивать верные имена.
    :param answers: куда сложить ответы модели как есть. Когда поручений не
        нашлось, это единственный способ понять почему: модель могла
        ответить прозой, по-английски или пересказать задание вместо
        ответа — и всё это выглядит одинаково, как пустой результат.
    :param journal: куда записать ход разбора по стадиям. Без него видно
        только начало и конец, и «модель не нашла» неотличимо от «нашла, а
        мы отсеяли»: пункта нет в обоих случаях.
    """
    collected: list[Task] = []
    total = len(chunks) or 1
    # До цикла: окон может не быть вовсе — на совещании, где ничего не
    # поручили, отбор по фразам не даст ни одного, и настройки всё равно
    # нужны дальше.
    settings = getattr(client, "settings", None)

    for position, chunk in enumerate(chunks, 1):
        title = f"Фрагмент {chunk.index} из {chunk.total}"
        json_mode = getattr(client, "settings", None) and client.settings.llm_json_mode
        report(progress, Step(name="chunk", title=title, share=(position - 1) / total))

        started = time.perf_counter()
        system, user = build_prompt(
            chunk,
            json_mode=bool(json_mode),
            extra=getattr(settings, "prompt_extra", "") or "",
            base=_own_prompt(settings),
        )
        try:
            reply = client.complete(
                system, user,
                json_mode=bool(json_mode),
                schema=TASKS_SCHEMA if json_mode else None,
            )
        except LLMError as exc:
            if not skip_failed:
                raise
            logger.warning("Фрагмент {}/{} пропущен: {}", chunk.index, chunk.total, exc)
            if journal is not None:
                journal.window(chunk, f"(запрос не удался: {exc})", 0)
            report(progress, Step(
                name="chunk",
                title=f"{title} — пропущен: {exc}",
                done=True,
                elapsed_s=round(time.perf_counter() - started, 1),
                share=position / total,
            ))
            continue

        if answers is not None:
            answers.append(reply.text)
        parsed = parse_tasks(reply.text, chunk=chunk.index)
        found = attach_source(
            _keep_sound(parsed, chunk.text, corpus or chunk.text), chunk
        )

        if reply.truncated:
            logger.warning(
                "Фрагмент {}: ответ обрезан по длине, спасено поручений {}. "
                "Помогает больший llm_max_tokens или фрагменты помельче.",
                chunk.index, len(parsed),
            )

        # Модель ответила по-английски, и от фрагмента ничего не осталось.
        # Просьба в промпте её не удержала, но повтор с требованием в самом
        # конце запроса — обычно да: последнее указание весит больше всего.
        if parsed and not found and not any(is_russian(t.what) for t in parsed):
            logger.info("Фрагмент {}: ответ по-английски, повторяю запрос", chunk.index)
            try:
                again = client.complete(
                    system,
                    f"{user}\n\nВНИМАНИЕ: ответ должен быть на русском языке.",
                    json_mode=bool(json_mode),
                    schema=TASKS_SCHEMA if json_mode else None,
                )
            except LLMError as exc:
                logger.warning("Повтор не удался: {}", exc)
            else:
                if answers is not None:
                    answers.append(again.text)
                found = attach_source(
                    _keep_sound(
                        parse_tasks(again.text, chunk=chunk.index),
                        chunk.text,
                        corpus or chunk.text,
                    ),
                    chunk,
                )
        logger.info(
            "Фрагмент {}/{}: поручений {}, ответ за {} с",
            chunk.index, chunk.total, len(found), reply.elapsed_s,
        )
        if journal is not None:
            journal.window(chunk, reply.text, len(found))
        collected.extend(found)
        report(progress, Step(
            name="chunk",
            title=f"{title} — поручений {len(found)}",
            done=True,
            elapsed_s=round(time.perf_counter() - started, 1),
            share=position / total,
        ))

    whole = dedupe(collected)
    if journal is not None:
        journal.step(
            "Снятие буквальных повторов", collected, whole,
            why="Окна пересекаются соседними фразами, и одно поручение "
            "приезжает из двух окон слово в слово.",
        )
    merged = keep_meaningful(whole)
    if len(merged) != len(whole):
        logger.info(
            "Отсеяно как обломок из одного слова: {}", len(whole) - len(merged)
        )
    if journal is not None:
        journal.step(
            "Отсев обломков из одного слова", whole, merged,
            why="«Подтвердить» без предмета — не задание: ни разослать, ни "
            "спросить.",
        )
    heard = keep_directives(merged)
    if len(heard) != len(merged):
        # Счёт в журнал: отсев молчком выглядит так, будто модель ничего не
        # нашла, а видеть надо разницу между «не нашла» и «нашла не то».
        logger.info(
            "Отсеяно как не поручение: {} из {} — в реплике нет ни просьбы, "
            "ни повелительного наклонения",
            len(merged) - len(heard), len(merged),
        )
    if journal is not None:
        journal.step(
            "Отсев не поручений", merged, heard,
            why="В реплике-источнике нет ни просьбы, ни повелительного "
            "наклонения — значит, поручения в ней не звучало.",
        )
    single = one_per_place(heard)
    if len(single) != len(heard):
        logger.info("Склеено по месту разговора: {}", len(heard) - len(single))
    if journal is not None:
        journal.step(
            "Склейка по месту разговора", heard, single,
            why="Одно и то же поручение, выписанное из двух пересекающихся "
            "окон разными словами.",
        )
    if settings is None or getattr(settings, "one_task_per_phrase", True):
        together = one_per_phrase(single)
        if len(together) != len(single):
            logger.info(
                "Сведено в один пункт как сказанное одной фразой: {} -> {}",
                len(single), len(together),
            )
        if journal is not None:
            journal.step(
                "Сведение сказанного одной фразой", single, together,
                why="Несколько действий в одной фразе — один пункт: адресат "
                "один и срок один.",
            )
        single = together
    named = with_due(with_addressee(single, chair=chair))
    added = sum(1 for was, now in zip(single, named) if not was.who and now.who)
    if added:
        logger.info("Исполнитель взят из обращения: {} поручений", added)
    dated = sum(1 for was, now in zip(single, named) if not was.due and now.due)
    if dated:
        logger.info("Срок взят из реплики: {} поручений", dated)
    if journal is not None:
        journal.step(
            "Исполнитель и срок из реплики", single, named,
            why=f"Исполнитель взят из обращения: {added}. "
            f"Срок взят из реплики: {dated}. Пункты при этом не убывают.",
        )
    single = named
    if settings is not None and getattr(settings, "merge_similar", False) and single:
        before = single
        single = merge_similar(single, client, json_mode=bool(json_mode))
        if journal is not None:
            journal.step(
                "Сведение повторов моделью", before, single,
                why="Одно поручение, сказанное разными словами в разных "
                "окнах. Решает модель, сливает код.",
            )
    if settings is not None and getattr(settings, "verify_tasks", False) and single:
        report(progress, Step(name="verify", title="Проверяю поручения", share=1.0))
        before = single
        single = verify(single, client, json_mode=bool(json_mode))
        if journal is not None:
            journal.step(
                "Проверка «поручение или доклад»", before, single,
                why="По каждому пункту модель отвечала, поручение это или "
                "изложение доклада. Снятое — то, что она сочла докладом.",
            )
    return single


def _own_prompt(settings) -> str:
    """Своё системное указание из файла, если оно задано."""
    path = getattr(settings, "prompt_file", None)
    if not path:
        return ""
    try:
        return Path(path).read_text(encoding="utf-8-sig")
    except OSError as exc:
        logger.warning("Не прочитать {}, беру встроенное указание: {}", path, exc)
        return ""


def attach_source(tasks: list[Task], chunk: Chunk) -> list[Task]:
    """Привязывает поручение к тому месту, откуда оно выписано.

    Ищется не реплика, а предложение внутри неё. Разница решающая: после
    разметки по голосам реплика — это целое выступление на десять минут, и
    её начало не говорит ничего. Восемь поручений из одной речи получали
    одну и ту же отметку времени, перематывать по которой некуда.

    Отметка внутри выступления считается по доле текста: точной её сделать
    нельзя — время известно только для реплики целиком, — но попадает она в
    нужную минуту, а не в начало доклада.
    """
    attached = []
    for task in tasks:
        words = _significant(task.what)
        found = _best_sentence(words, chunk) if words else None
        block = found.block if found else None
        attached.append(Task(
            what=task.what,
            who=task.who if _who_holds(task.who, block, chunk) else "",
            due=task.due, chunk=task.chunk,
            at=found.at if found else None,
            quote=found.quote if found else "",
            context=found.context if found else "",
            said_by=found.said_by if found else "",
            region=task.region, due_date=task.due_date,
        ))
    return attached


#: Сколько реплик вокруг считается тем же местом разговора. Адресата часто
#: называют в соседней: «Сергей Анатольевич, подготовьте» — и следом сам
#: Сергей Анатольевич отвечает, а поручение прицепляется к его словам.
NEARBY = 1


def _who_holds(who: str, block, chunk: Chunk) -> bool:
    """Назван ли исполнитель там же, где прозвучало поручение.

    Раньше фамилия принималась, если встречалась где угодно в стенограмме.
    Для двухчасового совещания это почти не проверка: чаще всех звучит имя
    ведущего, и он оказывался адресатом там, где сам же и говорил.

    Годятся два случая. Либо человека назвали в этой самой реплике — «Сергей
    Анатольевич, прошу подготовить». Либо он и есть говорящий: взялся
    сделать сам, и это тоже поручение.

    Неверный адресат хуже пустого. Пустой заставляет уточнить перед
    рассылкой, неверный уходит в рассылку как есть.
    """
    if not who:
        return False
    if who in COLLECTIVE_NAMES:
        # Проверка ищет фамилию рядом с поручением, чтобы не подписать чужого
        # человека. К «всем регионам» она неприменима: их не называют, к ним
        # обращаются.
        return True
    if block is None:
        return True
    for near in _around(block, chunk):
        if _named_in(near.text or "", who) or _named_in(near.speaker or "", who):
            return True
    return False


def _around(block, chunk: Chunk) -> list:
    """Реплика и её соседи — то, что считается одним местом разговора."""
    try:
        at = chunk.blocks.index(block)
    except ValueError:  # pragma: no cover — блок всегда из этого куска
        return [block]
    return chunk.blocks[max(0, at - NEARBY):at + NEARBY + 1]


def _named_in(text: str, who: str) -> bool:
    """Встречается ли имя в тексте, с поправкой на падежи.

    Сравниваются основы: «Огородникова» и «Огородниковой» — один человек, а
    точное совпадение их не признаёт.
    """
    lowered = text.lower()
    for word in re.findall(r"\w+", who.lower()):
        if len(word) < 4:
            continue
        if (word[:-2] if len(word) > 5 else word) in lowered:
            return True
    return False


@dataclass
class Source:
    """Место в стенограмме, откуда выписано поручение."""

    at: float | None
    quote: str
    #: Цитата с соседними фразами — кусок, который читает человек.
    context: str
    said_by: str
    block: object


#: Сколько фраз вокруг цитаты входит в кусок. Одной хватает: срок и адресат
#: стоят вплотную — «Просьба подтвердить» и следом «цех компостирования на
#: 95,7% готов». Две уже тянут за собой соседнее поручение.
CONTEXT_SENTENCES = 1


def _best_sentence(words: set[str], chunk: Chunk) -> Source | None:
    """Предложение, больше всего похожее на поручение.

    Совпадение считается долей от слов поручения, а не от слов предложения:
    иначе выигрывает самое длинное, в котором просто больше слов. При равном
    счёте берётся короткое — цитата в одну строку полезнее абзаца.
    """
    best: Source | None = None
    best_score = 0.0
    for block in chunk.blocks:
        sentences = _sentences(block.text)
        offset = 0
        for position, sentence in enumerate(sentences):
            share = len(words & _significant(sentence)) / len(words)
            # Короткое при равном счёте: длинное предложение попадает в счёт
            # случайными совпадениями, и цитата из него нечитаема.
            better = share > best_score or (
                share == best_score and best is not None and len(sentence) < len(best.quote)
            )
            if share > 0 and better:
                best_score = share
                best = Source(
                    at=_moment(block, offset),
                    quote=_short_quote(sentence),
                    context=_with_neighbours(sentences, position),
                    said_by=block.speaker,
                    block=block,
                )
            offset += len(sentence)
    return best


def _with_neighbours(sentences: list[str], position: int) -> str:
    """Цитата вместе с соседними фразами — тем куском, что читает человек."""
    start = max(0, position - CONTEXT_SENTENCES)
    return " ".join(sentences[start:position + CONTEXT_SENTENCES + 1]).strip()


def _sentences(text: str) -> list[str]:
    """Режет реплику на предложения. Грубо — точки хватает."""
    parts = re.split(r"(?<=[.!?])\s+", (text or "").strip())
    return [part for part in parts if part]


def _moment(block, offset: int) -> float | None:
    """Где внутри реплики находится это место, по доле текста.

    Приблизительно, и точнее не получится: время известно только для реплики
    целиком. Но попасть в нужную минуту десятиминутного выступления это
    позволяет, а начало доклада — нет.
    """
    # Время у реплики может отсутствовать: стенограмму приносят и руками.
    start, end = block.start, block.end
    if start is None:
        return None
    length = len(block.text or "")
    if not length or end is None or end <= start:
        return start
    return start + (end - start) * (offset / length)


def _short_quote(text: str, limit: int = 220) -> str:
    """Цитата достаточной длины, чтобы понять, о чём речь, но не абзац."""
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + "…"


def _keep_sound(tasks: list[Task], source: str, corpus: str) -> list[Task]:
    """Отсеивает выдуманное и подчищает исполнителей.

    Поручение сверяется с тем фрагментом, откуда взято, а исполнитель — со
    всей стенограммой: человека представляют один раз, а поручения он
    получает потом.
    """
    kept: list[Task] = []
    for task in tasks:
        if not is_russian(task.what):
            logger.info("Отброшено не по-русски: {}", task.what[:80])
            continue
        if not grounded(task, source):
            logger.warning("Отброшено как выдуманное, в стенограмме нет: {}", task.what[:80])
            continue
        kept.append(Task(
            what=task.what,
            who=clean_assignee(task.who, corpus),
            due=clean_due(task.due),
            chunk=task.chunk,
        ))
    return kept


GROUPS_SCHEMA = {
    "type": "object",
    "properties": {
        "groups": {"type": "array", "items": {"type": "array", "items": {"type": "integer"}}}
    },
    "required": ["groups"],
    "additionalProperties": False,
}

MERGE_SYSTEM = """Ты — секретарь совещания. Тебе дан список поручений, выписанных по
частям из одной стенограммы. Из-за деления на части одно и то же поручение могло
попасть в список дважды, разными словами.

Твоя задача — только сгруппировать повторы. Верни номера поручений, которые
означают одно и то же:

{"groups": [[1, 4], [2], [3, 5, 6]]}

Правила:
1. Каждый номер встречается ровно один раз.
2. Поручение без пары — группа из одного номера.
3. Не пиши текст поручений, только номера. Ничего не добавляй и не выбрасывай.
4. Разные поручения одному человеку — это разные поручения, не объединяй их."""


def merge_similar(
    tasks: list[Task],
    client: LLMClient,
    *,
    json_mode: bool = True,
) -> list[Task]:
    """Сводит поручения, сказанные разными словами.

    Правила снимают только буквальные повторы, а фрагменты пересекаются, и
    одно поручение приезжает дважды: «подтвердить статус дорожной карты» и
    «проинформировать о текущем статусе дорожной карты». Понять, что это
    одно и то же, может только модель.

    Но решает она не всё: модель возвращает **номера**, а сливает записи код.
    Так она физически не может ни переписать поручение по-своему, ни
    выдумать новое, ни потерять то, о котором забыла, — не упомянутый номер
    остаётся сам по себе.
    """
    if len(tasks) < 2:
        return tasks

    listing = "\n".join(f"{i}. {t.as_line()}" for i, t in enumerate(tasks, 1))
    try:
        reply = client.complete(
            MERGE_SYSTEM, listing,
            json_mode=json_mode,
            schema=GROUPS_SCHEMA if json_mode else None,
        )
    except LLMError as exc:
        logger.warning("Свести повторы не удалось, оставляю как есть: {}", exc)
        return tasks

    groups = _read_groups(reply.text, len(tasks))
    if not _grouping_is_sane(groups, len(tasks)):
        logger.warning(
            "Сведение повторов отвергнуто: {} поручений свелись бы к {}. "
            "Столько повторов в одном совещании не бывает — похоже, модель "
            "сгруппировала неродственное. Оставляю список как есть.",
            len(tasks), len(groups),
        )
        return tasks

    merged = [_merge_group(tasks, indexes) for indexes in groups]
    if len(merged) < len(tasks):
        logger.info("Повторы сведены: {} -> {}", len(tasks), len(merged))
    return merged


#: Насколько список вправе сжаться. Повторы берутся с границ фрагментов, и
#: их столько же, сколько границ: на семи фрагментах это единицы, а не
#: две трети списка.
MERGE_FLOOR = 0.6

#: Больше трёх записей об одном поручении не бывает даже при нахлёсте.
MERGE_MAX_GROUP = 3


def _grouping_is_sane(groups: list[list[int]], count: int) -> bool:
    """Похоже ли сведение на правду.

    Мелкая модель, не поняв задачи, валит всё в две-три кучи — и список из
    восемнадцати поручений превращается в пять. Это не повторы, это потеря
    тринадцати поручений, и заметить её в готовом протоколе нельзя: он
    выглядит просто коротким.
    """
    if len(groups) < count * MERGE_FLOOR:
        return False
    return all(len(group) <= MERGE_MAX_GROUP for group in groups)


def _read_groups(answer: str, count: int) -> list[list[int]]:
    """Разбирает группы, добирая всё, о чём модель умолчала.

    Номер, не попавший ни в одну группу, становится своей группой: молчание
    модели не должно стоить поручения.
    """
    try:
        body = json.loads(answer[answer.find("{") : answer.rfind("}") + 1])
        raw = body.get("groups") or []
    except (ValueError, AttributeError):
        raw = []

    groups: list[list[int]] = []
    seen: set[int] = set()
    for group in raw:
        if not isinstance(group, list):
            continue
        clean = [int(n) - 1 for n in group if isinstance(n, int) and 1 <= n <= count]
        clean = [n for n in clean if n not in seen]
        if clean:
            groups.append(clean)
            seen.update(clean)

    groups.extend([[n] for n in range(count) if n not in seen])
    return sorted(groups, key=lambda g: g[0])


def _merge_group(tasks: list[Task], indexes: list[int]) -> Task:
    """Из нескольких записей об одном поручении — одна, самая полная."""
    group = [tasks[i] for i in indexes]
    # Берём самую подробную формулировку: короткая обычно теряет условие.
    best = max(group, key=lambda t: len(t.what))
    return Task(
        what=best.what,
        who=next((t.who for t in group if t.who), ""),
        due=next((t.due for t in group if t.due), ""),
        chunk=min(t.chunk for t in group),
        at=next((t.at for t in group if t.at is not None), None),
        quote=next((t.quote for t in group if t.quote), ""),
        context=next((t.context for t in group if t.context), ""),
        said_by=next((t.said_by for t in group if t.said_by), ""),
        region=next((t.region for t in group if t.region), ""),
        due_date=next((t.due_date for t in group if t.due_date), ""),
    )


VERIFY_SYSTEM = """Ты — секретарь совещания. Тебе дан кусок стенограммы и выписанный
из него пункт. Реши одно: поручение это или нет.

Поручение — когда на совещании кому-то велели что-то сделать: «подготовьте»,
«прошу подтвердить», «обеспечьте», «доложите».

Не поручение:
— изложение доклада и пересказ норм: «отходы должны накапливаться раздельно»,
  «регионы обязаны утвердить порядок» — это рассказ о правилах, а не задание;
— рассуждение, мнение, оценка: «работа организована системно»;
— вопрос ради сведений: «какая готовность объекта?»;
— ведение совещания: «переходим к следующему вопросу», «слово Иванову»;
— обрывок распознавания, в котором нет смысла.

Отвечай строго так, без единого слова вокруг:

{"order": true}

или

{"order": false}"""

#: Схема ответа проверяющего. Одно поле: мелкая модель, которой дали
#: свободу, вместо решения пересказывает кусок стенограммы.
VERDICT_SCHEMA = {
    "type": "object",
    "properties": {"order": {"type": "boolean"}},
    "required": ["order"],
    "additionalProperties": False,
}

#: Сколько списку позволено ужаться на проверке. Мелкая модель, не поняв
#: задачи, отвечает «нет» подряд, и протокол выходит пустым — а пустой
#: протокол выглядит так, будто на совещании ничего не поручали.
VERIFY_FLOOR = 0.3


def verify(
    tasks: Sequence[Task],
    client: LLMClient,
    *,
    json_mode: bool = True,
) -> list[Task]:
    """Спрашивает модель по каждому пункту: поручение это или доклад.

    Правилами это уже не отделить. «Интересные нормы касаются того, в каком
    виде отходы должны выноситься на площадки» — изложение чужого документа,
    а «должны» в нём неотличимо от требования; такие пункты и составляют
    теперь основной мусор.

    Спрашивается по одному и коротко: вопрос «да или нет» о куске в сотню
    токенов мелкая модель решает заметно надёжнее, чем выписывает поручения
    из куска в четыре тысячи. Отвечать ей позволено ровно одним полем.

    Сбой запроса — пункт остаётся: молчание сервера не повод вычеркнуть
    поручение.
    """
    if not tasks:
        return list(tasks)

    kept: list[Task] = []
    dropped: list[Task] = []
    for task in tasks:
        source = task.context or task.quote
        if not source:
            kept.append(task)
            continue
        question = f"Кусок стенограммы:\n{source}\n\nВыписанный пункт: {task.what}"
        try:
            reply = client.complete(
                VERIFY_SYSTEM, question,
                json_mode=json_mode,
                schema=VERDICT_SCHEMA if json_mode else None,
            )
        except LLMError as exc:
            logger.warning("Проверка пункта не удалась, оставляю: {}", exc)
            kept.append(task)
            continue
        (dropped if _said_no(reply.text) else kept).append(task)

    if len(kept) < len(tasks) * VERIFY_FLOOR:
        logger.warning(
            "Проверка отвергнута: из {} поручений уцелело бы {}. Столько "
            "мусора в списке не бывает — похоже, модель не поняла вопроса. "
            "Оставляю список как есть.",
            len(tasks), len(kept),
        )
        return list(tasks)

    for task in dropped:
        logger.info("Отсеяно проверкой как не поручение: {}", task.what[:80])
    if dropped:
        logger.info("Проверка сняла {} из {}", len(dropped), len(tasks))
    return kept


def _said_no(answer: str) -> bool:
    """Ответила ли модель «это не поручение».

    Разбор снисходительный ко всему, кроме сути: ответ может приехать
    словом, а не JSON. Непонятый ответ считается согласием — вычёркивать
    поручение из-за того, что мы не разобрали ответ, нельзя.
    """
    text = (answer or "").strip().lower()
    if not text:
        return False
    try:
        body = json.loads(text[text.find("{") : text.rfind("}") + 1])
    except ValueError:
        body = None
    if isinstance(body, dict) and "order" in body:
        return body["order"] is False
    return text.startswith(("нет", "false", "no"))


#: Насколько два поручения должны совпасть словами, чтобы считаться одним.
#: Порог высокий намеренно. Поручения из одного совещания похожи между собой
#: по построению: «приступить к строительству объекта КПО Нижневартовска» и
#: «приступить к строительству объекта утилизации в Тюменской области»
#: совпадают на три четверти, а это разные стройки в разных регионах.
#: Различают их одно-два слова, и порог должен быть выше, чем цена этих слов.
SAME_TASK = 0.85

#: Короче этого поручения не сравниваются: на трёх словах любое совпадение
#: случайно.
MIN_WORDS_TO_COMPARE = 4


def _looks_same(one: Task, other: Task) -> bool:
    """Об одном ли эти два поручения.

    Сравниваются значимые слова. Проверка тупая и потому предсказуемая: она
    ловит пересказ теми же словами, а решать про разные слова — работа
    модели, и она с ней, как выяснилось, не справляется.
    """
    left, right = _significant(one.what), _significant(other.what)
    if min(len(left), len(right)) < MIN_WORDS_TO_COMPARE:
        # На трёх словах совпадение ничего не значит: «работать с регионами»
        # и «работать с региональными операторами» совпадут полностью, а это
        # разные поручения.
        return False
    common = left & right
    return len(common) / min(len(left), len(right)) >= SAME_TASK


def dedupe(tasks: Iterable[Task]) -> list[Task]:
    """Убирает повторы.

    Повторы неизбежны: куски стенограммы идут с нахлёстом, поэтому реплика на
    границе попадает в модель дважды. Без этого шага каждое второе поручение
    в протоколе двоилось бы.

    Из двух одинаковых остаётся то, где больше сведений: если в одном
    фрагменте модель увидела задачу без срока, а в другом — со сроком, срок
    сохраняется.
    """
    kept: list[Task] = []
    for task in tasks:
        twin = next(
            (i for i, other in enumerate(kept)
             if other.key == task.key or _looks_same(other, task)),
            None,
        )
        if twin is None:
            kept.append(task)
            continue
        # Из двух записей об одном поручении берётся подробная, а
        # исполнитель и срок — оттуда, где они есть.
        old_task = kept[twin]
        kept[twin] = Task(
            what=max(old_task.what, task.what, key=len),
            who=old_task.who or task.who,
            due=old_task.due or task.due,
            chunk=min(old_task.chunk, task.chunk) or old_task.chunk,
            at=old_task.at if old_task.at is not None else task.at,
            quote=old_task.quote or task.quote,
            context=old_task.context or task.context,
            said_by=old_task.said_by or task.said_by,
            region=old_task.region or task.region,
            due_date=old_task.due_date or task.due_date,
        )
    return kept


def _parse_json(text: str, chunk: int) -> list[Task] | None:
    """Разбирает ответ в JSON, если это он.

    ``None`` означает «это не JSON» — тогда работает разбор по строкам.
    Пустой список — «JSON разобран, поручений в нём нет»; это разные вещи,
    и путать их нельзя.
    """
    start = text.find("{")
    end = text.rfind("}")
    if start < 0 or end <= start:
        return None
    try:
        body = json.loads(text[start : end + 1])
    except ValueError:
        body = _salvage(text[start:])
        if body is None:
            return None
    if not isinstance(body, dict):
        return None

    items = body.get("tasks")
    if not isinstance(items, list):
        return None

    tasks = []
    for item in items:
        if not isinstance(item, dict):
            continue
        what = str(item.get("what") or "").strip()
        if what:
            tasks.append(Task(
                what=what,
                who=_clean(str(item.get("who") or "")),
                due=_clean(str(item.get("due") or "")),
                chunk=chunk,
            ))
    return tasks


def _salvage(text: str) -> dict | None:
    """Собирает поручения из оборванного ответа.

    Модель упирается в предел длины и обрывается на полуслове: JSON не
    закрыт, и целиком он не разбирается. Но поручения, успевшие уместиться,
    целы — терять их вместе с последним, недописанным, обидно: это минута
    работы модели, выброшенная из-за одной скобки.
    """
    items = []
    for match in re.finditer(r"\{[^{}]*\}", text):
        try:
            item = json.loads(match.group(0))
        except ValueError:
            continue
        if isinstance(item, dict) and item.get("what"):
            items.append(item)
    return {"tasks": items} if items else None


def _build(fields: dict[str, str], chunk: int) -> Task:
    return Task(
        what=fields.get("what", "").strip(),
        who=_clean(fields.get("who", "")),
        due=_clean(fields.get("due", "")),
        chunk=chunk,
    )


def _clean(value: str) -> str:
    """Пустое значение и «не указано» — одно и то же.

    Строку «не указано» нельзя оставлять как есть: в отчёте она выглядит
    заполненным полем, и таблицу поручений уже не отфильтровать по тем, где
    исполнителя действительно нет.
    """
    value = (value or "").strip().strip(".").strip()
    return "" if value.lower() in _NOT_SET else value


def _field_of(label: str) -> str | None:
    lowered = label.strip().lower()
    for field, aliases in _FIELD_ALIASES.items():
        if lowered in aliases:
            return field
    return None


def _normalize(text: str) -> str:
    return re.sub(r"[^\w\s]", "", (text or "").lower()).strip()
