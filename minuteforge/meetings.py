"""Папка заседания: как её узнать, что в ней лежит и куда класть результат.

Раскладка заседания — соглашение, а не структура данных. Папку заводит
человек: кладёт в неё присланное секретарём и запись, а результат ждёт там
же. Поэтому здесь не проверки точных имён, а приметы, и любой довольно:
свои имена приложение пишет само, а имя папки с присланным придумывает
человек, и требовать от него точного написания значит терять материалы
молча.

Жило это в интерфейсе, пока запускали только им. Командная строка клала
стенограмму в ``output_dir`` независимо от того, где лежит запись, — и то же
заседание выходило разложенным двумя разными способами. Раскладка одна,
значит и код один.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

#: Чем папка заседания отличается от любой другой: в ней заведено своё
#: хозяйство. «secretary» — присланное секретарём, «prep» — посчитанное до
#: совещания, «runs» — прогоны.
MEETING_MARKS = ("secretary", "prep", "runs")

#: Наше, а не секретарское: прогоны и посчитанное до совещания. Внутрь не
#: смотрим — иначе протокол прошлого прогона вернётся как материал, а звук,
#: вытащенный прошлым прогоном, — как запись совещания.
OURS = ("runs", "prep")

#: Чем присылают материалы к совещанию.
MATERIAL_SUFFIXES = (".docx", ".xlsx", ".pdf")

#: Протокол лежит в папке заседания наравне с присланным, но материалом не
#: является: он не вход, а выход, и по нему сверяют разбор. Попав в
#: материалы, он уходит моделью в тезисы — то есть в подсказку распознаванию
#: попадает готовый ответ.
NOT_MATERIALS = ("протокол",)

#: Что считаем записью совещания. Шире, чем ``VIDEO_SUFFIXES`` в pipeline:
#: там перечислено то, из чего сперва извлекается звук, а здесь — то, что
#: вообще можно отдать на распознавание.
MEDIA_SUFFIXES = {
    ".mp4", ".avi", ".mov", ".mkv", ".webm", ".m4v", ".wav", ".m4a", ".mp3",
}

#: Насколько высоко подниматься от файла в поисках папки заседания. Два
#: этажа: запись лежит в самой папке заседания или в присланном секретарём,
#: а стенограмма — ещё и в папке прогона, то есть в «runs/<прогон>».
UP = 2


def materials_in(folder: Path) -> list[Path]:
    """Документы секретаря по заседанию.

    Смотрим в саму папку заседания и на этаж вглубь — в любую подпапку,
    кроме наших. Имя подпапки значения не имеет, и это намеренно:
    «secretary» — соглашение раскладки, а заводит папку человек и назовёт её
    как придётся: «Секретарь», «от секретаря», «Материалы». Требовать
    точного написания значит терять материалы молча — хуже этого здесь
    ничего нет, потому что пропажа выглядит как «файлов не прислали».

    У заседаний, разложенных до этой раскладки, присланное лежит прямо в
    папке — потому корень и смотрится наравне с подпапками.
    """
    return _sent_here(folder) + _sent_below(folder)


def _sent_here(place: Path) -> list[Path]:
    """Присланное, лежащее прямо в этой папке."""
    place = Path(place)
    if not place.is_dir():
        return []
    try:
        return sorted(
            path for path in place.glob("*")
            if path.suffix.lower() in MATERIAL_SUFFIXES
            and not path.name.startswith("~$")
            and not _a_protocol(path.stem)
        )
    except OSError:
        # Общий диск отвалился посреди обхода. Материалы — не то, ради чего
        # стоит ронять расчёт: о недоступности скажет проверка папки.
        return []


def _a_protocol(stem: str) -> bool:
    """Протокол это или присланное к совещанию.

    Подписанный человеком начинается с «протокол»: «протокол.docx»,
    «Протокол заседания 27.08.docx». Наш — им кончается: имя несёт метку
    прогона впереди, «2026-10-01_1150_qwen3_протокол.docx», а свежий в корне
    заседания зовётся «последний-протокол». Прежде проверялось только
    начало, и наши собственные протоколы в материалы проходили.

    Концы, а не вхождение где угодно: «Выписка из протокола № 5.docx» —
    присланное к совещанию, и терять её нельзя. Пропажа материала выглядит
    как «файлов не прислали», и хуже этого здесь ничего нет.
    """
    low = stem.lower()
    return low.startswith(NOT_MATERIALS) or low.endswith(NOT_MATERIALS)


def _sent_below(folder: Path) -> list[Path]:
    """Присланное, лежащее в подпапке.

    Примета именно папки заседания, а не папки с присланным: у самой папки
    секретаря подпапок с docx нет, и по этой примете её от заседания видно.
    Без неё поиск останавливался этажом ниже — на «Секретарь», — и результат
    ложился внутрь присланного.
    """
    folder = Path(folder)
    if not folder.is_dir():
        return []
    try:
        inside = [
            path for path in sorted(folder.iterdir())
            if path.is_dir() and path.name.lower() not in OURS
        ]
    except OSError:
        return []
    return sorted(path for place in inside for path in _sent_here(place))


def is_meeting(folder: Path, *, meetings_dir: Path | None = None) -> bool:
    """Папка заседания это или обычная.

    Примет три, и любой довольно. Своё хозяйство — «runs», «prep»,
    «secretary»: имена наши, пишутся кодом, и спрашивать о них некого.
    Материалы секретаря — их папка названа человеком и зовётся как придётся,
    потому и ищутся они, а не папка с точным именем. И место: всё, что лежит
    папкой прямо в папке заседаний, — заседание по самой раскладке.

    Строгая проверка одних только наших имён ошибалась молча и дважды:
    прогон ложился не в «runs», а россыпью в папку заседания, и стенограмма
    заседания в её корень не попадала вовсе — а её там и ждут.

    :param meetings_dir: папка заседаний. Не задана — остаются две первые
        приметы: по месту узнать заседание не из чего.
    """
    if _the_meetings_folder(folder, meetings_dir):
        return False
    return _plainly(folder, meetings_dir) or bool(materials_in(folder))


def _the_meetings_folder(folder: Path, meetings_dir: Path | None) -> bool:
    """Папка заседаний целиком — не заседание, а их хранилище.

    Примет в ней полно: материалы находятся в соседнем заседании этажом
    ниже. Сказать это надо прямо, иначе результат ляжет в её корень — то
    есть в корень общего диска, рядом со всеми заседаниями разом.
    """
    return meetings_dir is not None and Path(folder) == Path(meetings_dir)


def _plainly(folder: Path, meetings_dir: Path | None) -> bool:
    """Приметы, которые с папкой внутри заседания не спутать.

    Своё хозяйство и место в папке заседаний — это про саму папку заседания.
    Материалы же видны и из папки с присланным, и потому в поиске снизу
    вверх идут не наравне с этими двумя, а после них.
    """
    folder = Path(folder)
    if _the_meetings_folder(folder, meetings_dir):
        return False
    if any((folder / mark).is_dir() for mark in MEETING_MARKS):
        return True
    if meetings_dir is not None and folder.parent == Path(meetings_dir):
        return folder.is_dir()
    return False


def meeting_near(
    file: Path | None, *, meetings_dir: Path | None = None, up: int = UP
) -> tuple[Path | None, list[Path]]:
    """Папка заседания и материалы секретаря в ней.

    Идём от файла вверх, но приметы разбираем по силе, а не по этажу:
    сильная примета верхнего этажа важнее слабой нижнего. Иначе ошибались
    все три способа по очереди — поиск по одним нашим именам уводил этажом
    выше, в папку заседаний целиком, где материалы находились в соседнем
    заседании; поиск по одним материалам — этажом ниже, на папку с
    присланным, и результат ложился внутрь материалов.

    Ничего похожего не нашлось — та папка, где лежит файл: заседание это или
    нет, результат кладут рядом с записью, а не в перевалочную папку
    приложения. Человеку надо сказать, куда он лёг, а не угадывать за него.
    """
    if file is None:
        return None, []
    here = Path(file).parent
    folders = [here, *list(here.parents)[:up]]

    # Приметы разбираются по силе, а не по этажу. Сперва те, что с папкой
    # внутри заседания не спутать, — и сразу по всем этажам: иначе слабая
    # примета нижнего этажа побеждала сильную верхнего, и поиск
    # останавливался на «Секретарь», а результат ложился внутрь присланного.
    for folder in folders:
        if _plainly(folder, meetings_dir):
            return folder, materials_in(folder)

    # Прежняя раскладка: присланное лежит прямо в папке заседания, подпапки
    # у него нет. Годится это только для той папки, с которой начали, —
    # этажом выше та же примета означала бы соседнее заседание.
    if _sent_here(here):
        return here, materials_in(here)

    # Присланное в подпапке — примета папки заседания, а не папки с
    # присланным: у самой папки секретаря подпапок с docx нет.
    for folder in folders:
        if _sent_below(folder) and not _the_meetings_folder(folder, meetings_dir):
            return folder, materials_in(folder)
    return here, []


def meeting_for(
    beside: Path | None,
    *,
    meetings_dir: Path | None = None,
    not_meetings: Sequence[Path] = (),
) -> tuple[Path | None, list[Path]]:
    """Папка, в которую ложится результат, — или None, если её не определить.

    None значит «класть некуда, зовите ``output_dir`` из настроек»: записи
    нет вовсе — так бывает, когда её загрузили через браузер и путь потерян,
    — либо лежит она там, где заседания не бывает.

    :param not_meetings: папки, заседанием не бывающие ни при каких приметах.
        Перевалочная и рабочая: в ``input_dir`` запись кладут на время, а в
        ``work_dir`` лежат наши промежуточные файлы и копия загруженной через
        браузер записи — складывать протокол ни в ту, ни в другую незачем.
    """
    folder, materials = meeting_near(beside, meetings_dir=meetings_dir)
    if folder is None or any(folder == Path(skip) for skip in not_meetings):
        return None, []
    return folder, materials


def meeting_folders(meetings_dir: Path) -> list[Path]:
    """Папки заседаний — всё, что лежит в папке заседаний папками.

    Новые сверху: заседания названы датой, и работают обычно с последним.
    """
    meetings_dir = Path(meetings_dir)
    if not meetings_dir.is_dir():
        return []
    try:
        return sorted(
            (path for path in meetings_dir.iterdir() if path.is_dir()),
            key=lambda path: path.name, reverse=True,
        )
    except OSError:
        # Общий диск отвалился посреди обхода. О недоступности скажет
        # проверка папки — пустой список лучше, чем упавший расчёт.
        return []


def recordings_in(meetings_dir: Path) -> list[Path]:
    """Записи совещаний, разложенные по папкам заседаний.

    Смотрим саму папку заседания и этаж вглубь: запись кладут и в корень
    папки, и вместе с присланным секретарём. Наши подпапки пропускаем — в
    «runs» лежат прогоны, и вытащенный звук прошлого разбора записью
    совещания не является.

    Нужно это там, где системным диалогом записи не выбрать: он открывается
    на той машине, где запущено приложение, и пришедший по ссылке с другого
    компьютера его не видит вовсе.
    """
    found: list[Path] = []
    for meeting in meeting_folders(meetings_dir):
        places = [meeting]
        try:
            places += [
                path for path in sorted(meeting.iterdir())
                if path.is_dir() and path.name.lower() not in OURS
            ]
        except OSError:
            continue
        for place in places:
            found += sorted(
                path for path in place.glob("*")
                if path.suffix.lower() in MEDIA_SUFFIXES
            )
    return found


def runs_root(out_dir: Path, *, meetings_dir: Path | None = None) -> Path:
    """Куда положить папку прогона.

    В папке заседания прогоны лежат в «runs», а не вперемешку с эталонными
    файлами: заседание — это документы секретаря и подписанный протокол,
    прогон — черновик машины, и путать их нельзя. Раньше прогон ложился в
    корень, а в «runs» его переносили руками — лишний перенос это лишняя
    возможность положить не туда.

    Папка не заседания — перевалочная, складывать там не во что, и прогон
    лежит сам по себе.
    """
    out_dir = Path(out_dir)
    return out_dir / "runs" if is_meeting(out_dir, meetings_dir=meetings_dir) else out_dir
