"""Чей вопрос разбирают: субъект из закрытого списка."""

from minuteforge.blocks import Block
from minuteforge.regions import at, find_subject, follow


def test_a_subject_is_recognised_through_its_cases():
    """«Архангельской», «Архангельская», «Архангельску» — один регион."""
    assert find_subject("Следующая у нас Архангельская область") == "Архангельская область"
    assert find_subject("Коллеги Ростовской области, просьба подтвердить") == "Ростовская область"
    assert find_subject("Следующий регион республика Чувашия") == "Чувашская Республика"


def test_a_mangled_name_is_not_a_subject():
    """Распознавание коверкает названия, и это главный довод за список.

    «Носоморской области» и «Синтуки» в списке нет — значит, графа
    останется пустой. Неверный адресат хуже пустого: пустой заставляет
    уточнить перед рассылкой, неверный уходит в рассылку как есть.
    """
    assert find_subject("Следующий регион у Носоморской области") == ""
    assert find_subject("Далее города Северно-Кавказского округа и Синтуки") == ""


def test_the_region_holds_until_the_next_one():
    """Регион объявляют один раз, а поручают потом четверть часа."""
    marks = follow([
        Block("SPEAKER_02", "Следующая у нас Архангельская область.", 100, 120),
        Block("SPEAKER_08", "Готовность 84%. Просьба подтвердить срок.", 200, 260),
        Block("SPEAKER_02", "Следующий регион Ростовская область.", 400, 420),
    ])

    assert at(marks, 250) == "Архангельская область"
    assert at(marks, 450) == "Ростовская область"
    assert at(marks, 50) == "", "до первого перехода адресата нет"


def test_an_unreadable_handover_clears_the_region():
    """Переход, в котором региона не разобрать, — тоже переход.

    «Далее города Северо-Кавказского округа и Синтуки»: что это Ессентуки,
    знает человек, а список видит только несовпадение. Оставить прежний
    регион значило бы подписать поручения Ессентуков Калмыкии.
    """
    marks = follow([
        Block("SPEAKER_02", "Следующий регион Калмыкия.", 100, 120),
        Block("SPEAKER_02", "Далее города Северо-Кавказского округа и Синтуки.", 300, 320),
        Block("SPEAKER_02", "Организуйте сейчас фотоотчёт.", 400, 420),
    ])

    assert at(marks, 200) == "Республика Калмыкия"
    assert at(marks, 400) == ""


def test_a_region_named_in_a_report_is_not_a_handover():
    """В докладе регионы называют десятками, и это не смена темы."""
    marks = follow([
        Block("SPEAKER_02", "Следующий регион Ростовская область.", 100, 120),
        Block("SPEAKER_12", "Для сравнения, в Тюменской области работа идёт лучше.", 200, 260),
    ])

    assert at(marks, 250) == "Ростовская область"


def test_a_region_is_matched_from_the_start_of_a_word():
    """«Считали деньги» — не Чита, «оказания услуг» — не Казань.

    Совпадение искалось подстрокой где угодно внутри слова, и «с-чит-али»
    находило Читу, «о-казан-ия» — Казань, «Т-омск-ая» — Омскую. В графе
    появлялся регион, которого в разговоре не было.
    """
    assert find_subject("Считали деньги? Килограмм краски сколько стоит?") == ""
    assert find_subject("чтобы этот вид оказания услуг не дискредитировал") == ""
    assert find_subject("И так нелепо чего-то тут читаете") == ""
    assert find_subject("По Томской области отчёт готов") == "Томская область"


def test_a_short_name_needs_the_end_of_the_word_too():
    """У короткой основы хвост должен быть длиной с падежное окончание.

    «Чит» — это Чита, но и начало «читать», «читаете», «читка». Три буквы
    границей слова не спасаются: она есть и там, и там.
    """
    assert find_subject("Коллеги из Читы на связи") == "Забайкальский край"
    assert find_subject("Чита докладывает") == "Забайкальский край"
    assert find_subject("Надо читать документы внимательно") == ""
    assert find_subject("Уфа на связи") == "Республика Башкортостан"
    assert find_subject("Уфимский район отчитался") == ""


def test_the_region_is_named_in_the_next_phrase():
    """Объявляют и называют порознь: «Следующий регион.» — и уже следующей
    фразой «Джамбулат Хизирович, Кисловодск». Пока смотрели только фразу
    перехода, весь первый час штаба оставался без региона."""
    marks = follow([
        Block("SPEAKER_02", "Хорошо. Следующий регион.", 100, 120),
        Block("SPEAKER_12", "Джамбулат Хизирович, Кисловодск. Коротко доложу.", 130, 200),
    ])

    assert at(marks, 150) == "Ставропольский край"


def test_a_quiet_handover_counts_only_when_the_region_is_named():
    """«Далее Иркутская область» — переход. «И так далее» — конец
    перечисления, и на итоговой реплике оно уводило разбор в тот регион,
    который случайно упомянут двумя фразами ниже."""
    marks = follow([
        Block("SPEAKER_12", "Далее Иркутская область на примере города Иркутск.", 100, 130),
        Block("SPEAKER_02", "Рассказывает стройнадзор и так далее.", 200, 230),
        Block("SPEAKER_02", "Как коллеги из Чувашии заявляют, объект ведём.", 240, 280),
    ])

    assert at(marks, 250) == "Иркутская область"


def test_moving_to_a_slide_does_not_clear_the_region():
    """«Переходим к фотоматериалу» сказано посреди разбора региона, и
    стирать по нему нельзя: регион не менялся."""
    marks = follow([
        Block("SPEAKER_12", "Далее Иркутская область на примере города Иркутск.", 100, 130),
        Block("SPEAKER_12", "Переходим к фотоматериалу. Видим переполненные контейнеры.", 200, 260),
    ])

    assert at(marks, 250) == "Иркутская область"


def test_moving_to_another_item_of_the_agenda_clears_the_region():
    """А переход к следующему вопросу повестки — конец разбора региона.
    Иначе поручения общей части достаются тому, кого разбирали до неё."""
    marks = follow([
        Block("SPEAKER_02", "Следующий регион Новосибирская область.", 100, 130),
        Block("SPEAKER_02", "Переходим к следующему вопросу, уважаемые коллеги.", 300, 330),
        Block("SPEAKER_11", "Прошу обратить внимание на региональные акты.", 400, 430),
    ])

    assert at(marks, 200) == "Новосибирская область"
    assert at(marks, 420) == "", "общая часть — не Новосибирская область"


def test_a_handover_inside_a_long_reply_counts_from_its_place():
    """Реплика ведущего бывает в две минуты, и «Следующий регион» в её
    конце, отнесённое к началу, отдавало следующему региону всё, что
    поручено в этой же реплике предыдущему."""
    marks = follow([
        Block("SPEAKER_02", "Следующий регион Ростовская область.", 0, 10),
        Block(
            "SPEAKER_02",
            "Дату ввода объекта назовите. " + "Разбираемся дальше. " * 40
            + "Следующий регион Чувашская Республика.",
            100, 200,
        ),
    ])

    assert at(marks, 110) == "Ростовская область", "начало реплики — ещё прежний регион"
    assert at(marks, 199) == "Чувашская Республика"
