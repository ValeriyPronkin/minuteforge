"""Чей вопрос разбирают: субъект из закрытого списка."""

from minuteforge.blocks import Block
from minuteforge.regions import at, find_subject, follow


def test_a_subject_is_recognised_through_its_cases():
    """«Архангельской», «Архангельская», «Архангельску» — один регион."""
    assert find_subject("Следующая у нас Архангельская область") == "Архангельская область"
    assert find_subject("Коллеги Ростовской области, просьба подтвердить") == "Ростовская область"
    assert find_subject("Следующий регион республика Чувашия") == "Чувашская Республика"


def test_a_mangled_name_is_not_a_subject():
    """Распознавание коверкает названия, и это главный довод за список.

    «Носоморской области» и «Синтуки» в списке нет — значит, графа
    останется пустой. Неверный адресат хуже пустого: пустой заставляет
    уточнить перед рассылкой, неверный уходит в рассылку как есть.
    """
    assert find_subject("Следующий регион у Носоморской области") == ""
    assert find_subject("Далее города Северно-Кавказского округа и Синтуки") == ""


def test_the_region_holds_until_the_next_one():
    """Регион объявляют один раз, а поручают потом четверть часа."""
    marks = follow([
        Block("SPEAKER_02", "Следующая у нас Архангельская область.", 100, 120),
        Block("SPEAKER_08", "Готовность 84%. Просьба подтвердить срок.", 200, 260),
        Block("SPEAKER_02", "Следующий регион Ростовская область.", 400, 420),
    ])

    assert at(marks, 250) == "Архангельская область"
    assert at(marks, 450) == "Ростовская область"
    assert at(marks, 50) == "", "до первого перехода адресата нет"


def test_an_unreadable_handover_clears_the_region():
    """Переход, в котором региона не разобрать, — тоже переход.

    «Далее города Северо-Кавказского округа и Синтуки»: что это Ессентуки,
    знает человек, а список видит только несовпадение. Оставить прежний
    регион значило бы подписать поручения Ессентуков Калмыкии.
    """
    marks = follow([
        Block("SPEAKER_02", "Следующий регион Калмыкия.", 100, 120),
        Block("SPEAKER_02", "Далее города Северо-Кавказского округа и Синтуки.", 300, 320),
        Block("SPEAKER_02", "Организуйте сейчас фотоотчёт.", 400, 420),
    ])

    assert at(marks, 200) == "Республика Калмыкия"
    assert at(marks, 400) == ""


def test_a_region_named_in_a_report_is_not_a_handover():
    """В докладе регионы называют десятками, и это не смена темы."""
    marks = follow([
        Block("SPEAKER_02", "Следующий регион Ростовская область.", 100, 120),
        Block("SPEAKER_12", "Для сравнения, в Тюменской области работа идёт лучше.", 200, 260),
    ])

    assert at(marks, 250) == "Ростовская область"
